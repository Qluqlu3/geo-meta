// 国道番号メタ: 国道の「おにぎり」標識(青い逆三角形の路線番号標識)に書かれた番号から
// 通過都道府県を引くためのデータ。元データ nationalRoutes.json は
// scripts/fetch-national-routes.mjs で日本語版Wikipediaから一度だけ生成したもの
// (ビルド時にネットワークは不要)。
//
// 3桁国道(101〜507号)は「指定された年ごとに、北から南へ順に番号を振る」という規則で
// 付番されているため、番号を見ただけで大まかな地域が分かる。個々の路線の通過都道府県まで
// 引ければ、標識1枚で数県〜1県(北海道なら振興局)まで絞り込める。

import raw from "./nationalRoutes.json";

export type NationalRoute = {
  n: number;
  year: number;
  from: string;
  to: string;
  /** 通過する都道府県のJISコード(1=北海道 … 47=沖縄県)。記事の記載順 */
  prefs: number[];
  km: number | null;
  /** 北海道内の通過振興局(「総合振興局/振興局」を除いた短縮名) */
  hokkaido?: string[];
  /** 起点・終点の緯度経度(自動車専用道路の一部の路線は欠落) */
  a?: [number, number];
  b?: [number, number];
};

export const nationalRoutesSource = raw.source;
export const nationalRoutes = raw.routes as NationalRoute[];
export const routeByNumber = new Map(nationalRoutes.map((r) => [r.n, r]));

