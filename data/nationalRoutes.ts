/** チャートの縦軸に使う代表緯度(起点・終点の中点。片方しか無ければその値) */
export function routeLatitude(r: NationalRoute): number | null {
  if (r.a && r.b) return (r.a[0] + r.b[0]) / 2;
  return r.a?.[0] ?? r.b?.[0] ?? null;
}

